"""Clone the repos a declared skill needs, unattended and without ever prompting.

A skill in `claude/skills.md` is a symlink into a `~/dev` repo. If that repo is not cloned on
this machine the link dangles, and **a dangling skill symlink does not error — Claude Code
simply does not see the skill.** So the capability vanishes silently, which is the whole
failure this module exists to end.

Three constraints shape every decision here, and none of them is negotiable:

1. **launchd cannot answer a prompt of any kind.** Not a passphrase, not a host-key
   confirmation, not a credential helper. So git is invoked with prompting disabled outright
   rather than merely "not expected" — a clone that *could* prompt would hang the sweep
   instead of failing it.
2. **The sweep runs unattended, on a timer.** Anything that fails must not be retried on every
   run, or a broken remote becomes a request storm against GitHub. Hence the hourly backoff, and hence
   the attempt being recorded *before* the clone runs, not after.
3. **Cloning writes to `~/dev`.** It is confined to repos already marked participating in
   `sync/registry.md`, which preserves MULTI_MACHINE_SYNC.md safety principle 4 (opt-in, not
   opt-out). A repo nobody opted in to is never fetched, even if a skill row names it.

**Why remote URLs are recorded rather than derived.** Most repos are
`git@github.com:Lmandrake/<Name>.git`, and an earlier draft of this module claimed *all* of
them were. That was false, and not hypothetically: one repo's origin is on
the private git host (`https://<private host>/<owner>/<Repo>.git`), which no pattern over `github.com`
produces. A guessed URL that is wrong yields a repo that fails to clone on every sweep
forever. The sweep already visits every repo, so it records each one's real `origin` into
`sync/remotes.md` — derived from truth, so it cannot drift. The pattern survives only as a
labelled fallback for a repo no machine has recorded yet, and the report always says which of
the two it used.

**Adopt before cloning.** A repo can live under a different folder name on one machine —
a repo registered as `Alpha` may sit at `~/dev/AlphaGame` on one machine. Cloning
by registry name would silently make a second, possibly large, copy beside the real one, and the sweep
would then commit to the copy nobody works in. So before any clone, the dev root is scanned
for a checkout whose `origin` matches the recorded remote (ssh/https, `.git` and case
normalised). Exactly one match is adopted — its path recorded in the registry's Machine paths
table for this machine. More than one is refused and reported: which copy is the real one is a
human's call, and `Alpha_old` beside `Alpha` is exactly that shape.
"""

import json
import os
import shutil
import subprocess
import time
from typing import Any, Dict, List, NamedTuple, Optional, Sequence, Tuple

from . import mdtable, paths

# A repo that failed is retried at most this often. Written when the sweep ran every ~127 s,
# when without it a dead remote would be dialled ~28 times an hour; still the right floor.
RETRY_INTERVAL_SECONDS = 3600

# Generous on purpose. A repo with ~1 GB of .git cannot finish in
# the two minutes an earlier draft allowed — and a timeout that a legitimate repo can never beat
# is not a safety limit, it is a repo that never arrives. The bound that actually matters is the
# per-repo hourly backoff, not this. A clone still cannot wedge the sweep: it is killed here,
# and its partial tree is removed so the retry is not blocked (see `clone`).
CLONE_TIMEOUT_SECONDS = 900

# At most one clone per sweep. Cloning is the only step here that is measured in tens of
# seconds, and serialising it bounds a sweep's worst case without needing a lock file —
# which is deliberate, because a lock inside the repo would propagate and wedge the other
# machine (the .git/index.lock wedge of 2026-09-01), and one outside it cannot coordinate
# across machines anyway.
MAX_CLONES_PER_SWEEP = 1

FALLBACK_TEMPLATE = "git@github.com:Lmandrake/%s.git"

REMOTES_HEADER = """# Repo remotes — recorded, not guessed

<!-- GENERATED by bin/sync.py. Do not hand-edit; it is rewritten from each repo's real
     `origin` as the sweep visits it.

     This exists so a machine missing a repo can clone it from recorded truth rather than a
     guessed URL pattern. Shared and fleet-wide rather than per-machine, because a repo's
     remote is the same everywhere — it changes only when a remote actually changes, so it
     does not churn.
-->
"""


class Attempt(NamedTuple):
    name: str
    ok: bool
    detail: str


def remotes_file() -> str:
    return os.path.join(paths.root(), "sync", "remotes.md")


def read_remotes(path: Optional[str] = None) -> Dict[str, str]:
    target = path or remotes_file()
    if not os.path.exists(target):
        return {}
    with open(target, encoding="utf-8") as handle:
        rows = mdtable.parse(handle.read())
    out = {}
    for row in rows:
        name = row.get("name", "").strip()
        url = row.get("remote", "").strip()
        if name and url:
            out[name] = url
    return out


def render_remotes(mapping: Dict[str, str]) -> str:
    lines = [REMOTES_HEADER, "| Name | Remote |", "|------|--------|"]
    for name in sorted(mapping):
        lines.append("| %s | %s |" % (name, mapping[name]))
    return "\n".join(lines) + "\n"


def observe_remote(repo_path: str) -> Optional[str]:
    """This repo's origin URL, or None if it has none / is not a repo."""
    try:
        result = subprocess.run(
            ["git", "-C", repo_path, "remote", "get-url", "origin"],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=15)
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    url = result.stdout.decode("utf-8", "replace").strip()
    return url or None


def normalize_remote(url: str) -> str:
    """A remote URL reduced to `host/owner/repo`, lowercased, for identity comparison.

    `git@github.com:Lmandrake/X.git`, `ssh://git@github.com/Lmandrake/X`, and
    `https://github.com/lmandrake/x.git` are the same repo; one machine may reach GitHub over
    https while another uses ssh, and treating them as different would both churn
    `sync/remotes.md` every sweep and defeat adopt-before-clone.
    """
    text = (url or "").strip()
    lowered = text.lower()
    for scheme in ("ssh://", "https://", "http://", "git://"):
        if lowered.startswith(scheme):
            text = text[len(scheme):]
            break
    else:
        # scp-like `user@host:path`
        if "@" in text.split("/")[0] and ":" in text:
            text = text.split("@", 1)[1].replace(":", "/", 1)
    if "@" in text.split("/")[0]:
        text = text.split("@", 1)[1]
    host, _, rest = text.partition("/")
    host = host.split(":")[0]  # drop a port
    rest = rest.strip("/")
    if rest.endswith(".git"):
        rest = rest[:-4]
    return ("%s/%s" % (host, rest)).lower()


def same_remote(left: str, right: str) -> bool:
    return bool(left) and bool(right) and normalize_remote(left) == normalize_remote(right)


def remote_host(url: str) -> str:
    """The host portion of `normalize_remote(url)` -- everything before the first "/".

    Built on `normalize_remote` rather than re-parsing the URL, so it inherits the same
    scp-like / ssh:// / https:// / user@ handling for free and cannot drift from it. Used by
    the sweep to ask `lib/machine.py`'s `host_reachable` whether THIS machine has any declared
    route to a repo's remote before touching it.

    `normalize_remote("")` reduces to `"/"` (an empty host and an empty path joined by the
    separator), so an empty or unparseable URL degrades to an empty host here too -- never a
    crash, and never a host string that could accidentally match something in machines.md.
    """
    host, _, _ = normalize_remote(url).partition("/")
    return host


def dev_root() -> str:
    return os.path.expanduser(os.environ.get("LODESTAR_DEV_ROOT", "~/dev"))


def checkouts(root: Optional[str] = None) -> List[Tuple[str, Optional[str]]]:
    """[(path, origin)] for every git checkout directly under the dev root. One level only.

    One level is the whole contract: every registered repo lives at `~/dev/<something>`, and
    walking deeper would find vendored and nested repos (RimWorld carries some) that must never
    be adopted as a registry row.
    """
    base = root or dev_root()
    found = []  # type: List[Tuple[str, Optional[str]]]
    try:
        names = sorted(os.listdir(base))
    except OSError:
        return found
    for name in names:
        full = os.path.join(base, name)
        if name.startswith(".") or not os.path.isdir(full):
            continue
        if not os.path.exists(os.path.join(full, ".git")):
            continue
        found.append((full, observe_remote(full)))
    return found


def find_checkouts(url: str, root: Optional[str] = None,
                   exclude: Sequence[str] = (),
                   inventory: Optional[List[Tuple[str, Optional[str]]]] = None) -> List[str]:
    """Checkouts under the dev root whose origin is `url`, minus `exclude` (realpaths).

    `inventory` is a precomputed `checkouts()`, so a sweep missing twenty repos reads each
    checkout's origin once rather than twenty times (it is a git call per repo, on a slow
    drive).
    """
    skip = set(os.path.realpath(path) for path in exclude)
    listing = checkouts(root) if inventory is None else inventory
    return [path for path, origin in listing
            if origin and same_remote(origin, url) and os.path.realpath(path) not in skip]


def former_instance(entry, root: Optional[str] = None,
                    inventory: Optional[List[Tuple[str, Optional[str]]]] = None
                    ) -> Optional[Tuple[str, str]]:
    r"""Is a PREVIOUS identity of this row still checked out here? (path, what matched) or None.

    🔴 **This is the consumer the `Former` column did not have, and without it renaming a
    registry row silently produces a second checkout.** Measured 2026-09-30: `Former` was
    parsed into `registry.Entry.former` by Phase 1 and read by no production code at all — the
    same inert-feature shape as `lib/enroll.py` before it got a caller.

    The failure it prevents, concretely. `clone_step` computes absence purely from the row's
    `Path`, and `adopt` matches an existing checkout on its **origin URL**. So renaming
    `OpenCodeCLI` → `DispatchOpenCode` makes every machine still holding `~/dev/OpenCodeCLI`
    see the row as absent, fail to adopt (the old checkout's origin is the old URL, which
    `normalize_remote` reduces to a *different* identity from the new one), and clone a second
    copy. Two checkouts of one repo, the stale one still pointing at the old remote. That is
    the `RimMaster`/`RimMandrake` failure recorded in `docs/SYNC_AGENT.md`, and it is exactly
    why the old row note said "do not rename this row yet".

    Matching is on either kind of former value, because a row's history carries both:

    - a former **name**, matched against the directory name under the dev root;
    - a former **remote URL**, matched through `same_remote` so a redirect or an `https` ↔
      `ssh` difference still counts.

    Returning a hit is deliberately NOT an invitation to adopt it in place. Lukas's first
    ruling on 2026-09-30 was that folders *are* renamed rather than left mismatched, so the
    caller's job is to stand aside and let the lifecycle converger do the rename. Adopting
    would record the old path as this machine's path and make the mismatch permanent.
    """
    former = tuple(getattr(entry, "former", ()) or ())
    if not former:
        return None

    listing = checkouts(root) if inventory is None else inventory
    destination = os.path.realpath(os.path.expanduser(entry.path))

    for path, origin in listing:
        if os.path.realpath(path) == destination:
            continue  # the row's own current path is not a FORMER identity
        name = os.path.basename(path.rstrip(os.sep))
        for value in former:
            value = value.strip()
            if not value:
                continue
            # A former name: compared case-insensitively, because APFS is case-insensitive
            # and `OpenCodeCLI` vs `opencodecli` are the same directory here.
            if "/" not in value and ":" not in value:
                if name.lower() == value.lower():
                    return (path, "former name %r" % value)
                continue
            if origin and same_remote(origin, value):
                return (path, "former remote %s" % value)
    return None


def _private_domain(host: str) -> bool:
    """The private host, or a host in a private address domain (`lib.boundary`)."""
    from . import boundary
    host = (host or "").lower()
    domains = boundary.address_domains() + ([boundary.host()] if boundary.host() else [])
    return any(host == d or host.endswith("." + d) for d in domains)


def census_form(url: str) -> str:
    """The form a remote takes in `sync/remotes.md`: https for the private host.

    The private-text guard refuses `git@<private host>:` as a private-domain address on an added
    line, which withheld this file from every sweep. The repo's real ssh remote is untouched;
    only the census row is spelled https. Other hosts keep whatever form was observed.
    """
    if url and is_ssh_url(url) and _private_domain(remote_host(url)):
        return "https://%s.git" % _keep_case_path(url)
    return url


def _keep_case_path(url: str) -> str:
    """`host/owner/repo` of an ssh URL with its original case and no `.git` suffix."""
    text = url.strip()
    for scheme in ("ssh://",):
        if text.lower().startswith(scheme):
            text = text[len(scheme):]
    if "@" in text.split("/")[0]:
        text = text.split("@", 1)[1]
    if "/" not in text.split(":")[0] and ":" in text:
        text = text.replace(":", "/", 1)
    return text[:-4] if text.endswith(".git") else text


def update_remotes(entries, path: Optional[str] = None) -> Tuple[Dict[str, str], bool]:
    """Fold this machine's observable origins into the recorded map.

    Returns (mapping, changed). Only ever *adds or corrects* entries for repos present here;
    a repo absent on this machine keeps whatever another machine recorded, which is the point
    — the machine that has it is the one that can describe it.
    """
    target = path or remotes_file()
    mapping = read_remotes(target)
    changed = False
    for entry in entries:
        repo_path = os.path.expanduser(entry.path)
        if not os.path.isdir(os.path.join(repo_path, ".git")):
            continue
        url = census_form(observe_remote(repo_path) or "") or None
        # Compared normalised: the same repo over https here and ssh on a Mac is not a change,
        # and recording it as one would flip the file back and forth on every sweep.
        recorded = mapping.get(entry.name, "")
        if url and not same_remote(recorded, url):
            mapping[entry.name] = url
            changed = True
        elif url and is_ssh_url(url) and not is_ssh_url(recorded):
            # Same repo, but this machine holds the SSH form and the row says https: upgrade it.
            # One-way on purpose (owner ruling 2026-10-09, "prefer SSH") — an https checkout
            # never downgrades an SSH row, so two machines cannot flip the row back and forth.
            mapping[entry.name] = url
            changed = True
    return mapping, changed


REMOTES_PATH = "sync/remotes.md"


def _remote_row(line: str) -> Optional[Tuple[str, str]]:
    cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
    if not line.strip().startswith("|") or len(cells) != 2 or not cells[0] or not cells[1]:
        return None
    return cells[0], cells[1]


def _merge_rows(left: List[str], right: List[str]) -> Tuple[Optional[List[str]], str]:
    """Union two sides of one conflict hunk of remote rows, preferring SSH per repo."""
    merged = {}  # type: Dict[str, str]
    for side in (left, right):
        for line in side:
            if not line.strip():
                continue
            row = _remote_row(line)
            if row is None:
                return None, "non-row line in conflict: %r" % line.strip()
            name, url = row
            have = merged.get(name)
            if have is None or have == url:
                merged[name] = url
                continue
            if not same_remote(have, url):
                return None, "%s: two different repos (%s vs %s)" % (name, have, url)
            if is_ssh_url(have) == is_ssh_url(url):
                kind = "SSH" if is_ssh_url(url) else "https"
                return None, "%s: two different %s forms (%s vs %s)" % (name, kind, have, url)
            merged[name] = have if is_ssh_url(have) else url
    return ["| %s | %s |" % (name, census_form(merged[name])) for name in sorted(merged)], ""


def resolve_remotes_conflict(text: str) -> Tuple[Optional[str], str]:
    """Resolve git conflict markers in `sync/remotes.md`, or refuse.

    Returns (resolved text, "") or (None, reason). Each conflicting row resolves to the `git@`
    form over the `https://` form of the same repo (owner ruling 2026-10-09: "Auto-rebase,
    prefer SSH"); a row only one side has is kept. Anything else — both SSH, both https, two
    different repos under one name, or a non-row line in a hunk — refuses, and the caller must
    abort the rebase and leave it for a human.
    """
    out = []  # type: List[str]
    sides = None  # type: Optional[List[List[str]]]
    current = None  # type: Optional[List[str]]
    keep = True
    lines = text.splitlines()
    for line in lines:
        if line.startswith("<<<<<<<"):
            if sides is not None:
                return None, "nested conflict markers"
            sides, current, keep = [[], []], None, True
            current = sides[0]
        elif sides is not None and line.startswith("|||||||"):
            keep = False  # diff3 base section: neither side's content
        elif sides is not None and line.startswith("=======") and line.strip() == "=======":
            keep = True
            current = sides[1]
        elif sides is not None and line.startswith(">>>>>>>"):
            rows, reason = _merge_rows(sides[0], sides[1])
            if rows is None:
                return None, reason
            out.extend(rows)
            sides = None
        elif sides is not None:
            if keep:
                current.append(line)
        else:
            out.append(line)
    if sides is not None:
        return None, "unterminated conflict"
    resolved = "\n".join(out) + ("\n" if text.endswith("\n") else "")
    names = [row[0] for row in (_remote_row(line) for line in out) if row]
    names = [name for name in names if name.lower() != "name" and not set(name) <= set("-")]
    if len(names) != len(set(names)):
        return None, "a repo is listed twice after resolution"
    return resolved, ""


def url_for(name: str, mapping: Dict[str, str]) -> Tuple[str, str]:
    """Return (url, source) where source is 'recorded' or 'guessed'."""
    if name in mapping:
        return mapping[name], "recorded"
    return FALLBACK_TEMPLATE % name, "guessed"


def load_attempts(path: Optional[str] = None) -> Dict[str, float]:
    """Machine-local, and pure cache: unreadable means 'never attempted', never a crash."""
    target = path or paths.clone_attempts_file()
    try:
        with open(target, encoding="utf-8") as handle:
            data = json.load(handle)
    except (OSError, ValueError):
        return {}
    if not isinstance(data, dict):
        return {}
    return dict((key, value) for key, value in data.items()
                if isinstance(value, (int, float)))


def save_attempts(attempts: Dict[str, float], path: Optional[str] = None) -> None:
    target = path or paths.clone_attempts_file()
    os.makedirs(os.path.dirname(target), exist_ok=True)
    tmp = target + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        json.dump(attempts, handle, indent=2, sort_keys=True)
    os.replace(tmp, target)


def may_attempt(name: str, attempts: Dict[str, float], now: Optional[float] = None,
                interval: int = RETRY_INTERVAL_SECONDS) -> bool:
    last = attempts.get(name)
    if last is None:
        return True
    return ((now if now is not None else time.time()) - last) >= interval


def clone(url: str, destination: str, timeout: int = CLONE_TIMEOUT_SECONDS) -> Tuple[bool, str]:
    """Clone non-interactively. Returns (ok, detail). Never raises, never prompts.

    Refuses an existing destination rather than merging into it: `git clone` into a non-empty
    directory fails anyway, and checking first turns a confusing git error into a clear one.
    """
    if os.path.exists(destination):
        return False, "destination already exists: %s" % destination

    environment = dict(os.environ)
    # Belt and braces, because a hang here is worse than a failure. GIT_TERMINAL_PROMPT stops
    # git asking for credentials; BatchMode stops ssh asking for a passphrase; StrictHostKey
    # checking=yes stops it asking to confirm an unknown host. Any of those unset would turn a
    # bad remote into a wedged sweep that launchd cannot rescue.
    environment["GIT_TERMINAL_PROMPT"] = "0"
    environment["GIT_ASKPASS"] = ""
    environment["SSH_ASKPASS"] = ""
    # The ssh options only when the URL is ssh. A machine with no ~/.ssh reaches GitHub over
    # https (rewriting git@ URLs with `url.<base>.insteadOf`), and there the options describe
    # a transport that is not in use.
    if is_ssh_url(url):
        environment.setdefault("GIT_SSH_COMMAND",
                               "ssh -o BatchMode=yes -o StrictHostKeyChecking=yes")

    os.makedirs(os.path.dirname(destination.rstrip("/")), exist_ok=True)
    try:
        result = subprocess.run(
            ["git", "clone", "--no-progress", url, destination],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            env=environment, timeout=timeout)
    except subprocess.TimeoutExpired:
        _discard_partial(destination)
        return False, "timed out after %ds" % timeout
    except OSError as error:
        _discard_partial(destination)
        return False, "could not run git: %s" % error

    if result.returncode == 0:
        return True, "cloned %s" % url
    _discard_partial(destination)
    message = (result.stderr or result.stdout).decode("utf-8", "replace").strip()
    return False, "git clone failed: %s" % (message.split("\n")[-1] if message else
                                            "exit %d" % result.returncode)


def is_ssh_url(url: str) -> bool:
    lowered = (url or "").strip().lower()
    if lowered.startswith("ssh://"):
        return True
    if "://" in lowered:
        return False
    head = lowered.split("/")[0]
    return "@" in head and ":" in lowered


def _discard_partial(destination: str) -> None:
    """Remove a failed clone's leftovers so the retry is not permanently blocked.

    Without this the module deadlocks itself on exactly the repos that need retrying: a killed
    or failed `git clone` leaves a partial directory behind, the next attempt hits the
    "destination already exists" refusal, and the repo can never arrive — no matter how many
    hours of backoff pass. Large repos are the likeliest to time out and so the likeliest to
    get stuck.

    Safe to delete because we reach here only in a failure path, having created the directory
    in this call: the exists-check at the top of `clone` guarantees nothing was there before.
    A tree containing real work therefore cannot be reached by this function.
    """
    if not os.path.isdir(destination):
        return
    try:
        shutil.rmtree(destination)
    except OSError:
        pass  # leave it; the next attempt will report "already exists" rather than crash


def adopt(entry, url: str, where: Optional[str], dry_run: bool, entries=(),
          root: Optional[str] = None,
          registry_path: Optional[str] = None,
          inventory: Optional[List[Tuple[str, Optional[str]]]] = None) -> Optional[Attempt]:
    """Adopt an existing checkout of `url` for `entry` instead of cloning. None: none found.

    Paths already registered for another row are excluded, so one checkout can never be
    adopted twice. Nothing is recorded without a machine to record it for.
    """
    from . import registry  # lazy: registry imports nothing from here, keep it that way

    others = [os.path.expanduser(other.path) for other in entries if other.name != entry.name]
    found = find_checkouts(url, root, exclude=others, inventory=inventory)
    if not found:
        return None
    if len(found) > 1:
        return Attempt(entry.name, False,
                       "not cloned: %d checkouts already have this origin (%s) — pick one and "
                       "add a Machine paths row for it" % (len(found), ", ".join(found)))
    target = found[0]
    if inventory is not None:
        # Claimed now, so a later row in the same pass cannot adopt the same checkout.
        inventory[:] = [item for item in inventory if item[0] != target]
    if not where:
        return Attempt(entry.name, False, "found %s with the same origin, but this machine has "
                                          "no role to record it under — not cloned" % target)
    if dry_run:
        return Attempt(entry.name, False, "would adopt existing checkout %s (origin matches) "
                                          "instead of cloning" % target)
    registry.record_machine_path(entry.name, where, target, registry_path)
    return Attempt(entry.name, True, "adopted existing checkout %s (origin matches); recorded "
                                     "as its path on %s" % (target, where))


def clone_missing(names: List[str], entries, mapping: Dict[str, str],
                  dry_run: bool = False, now: Optional[float] = None,
                  attempts_path: Optional[str] = None,
                  limit: int = MAX_CLONES_PER_SWEEP,
                  where: Optional[str] = None,
                  root: Optional[str] = None,
                  registry_path: Optional[str] = None) -> List[Attempt]:
    """Clone up to `limit` of `names`, honouring participation and backoff.

    `names` are repos a skill row needs. Anything not participating in the registry is
    reported as refused rather than silently skipped — a skill pointing at an unregistered
    repo is a table bug worth seeing.
    """
    by_name = dict((entry.name, entry) for entry in entries)
    attempts = load_attempts(attempts_path)
    stamp = now if now is not None else time.time()
    results = []  # type: List[Attempt]
    started = 0
    inventory = None  # type: Optional[List[Tuple[str, Optional[str]]]]

    for name in names:
        entry = by_name.get(name)
        if entry is None:
            results.append(Attempt(name, False,
                                   "not in sync/registry.md as participating — not cloned"))
            continue
        destination = os.path.expanduser(entry.path)
        if os.path.exists(destination):
            continue  # another sweep, or a human, got there first
        url, source = url_for(name, mapping)
        if inventory is None:
            inventory = checkouts(root)
        adopted = adopt(entry, url, where, dry_run, entries, root, registry_path, inventory)
        if adopted is not None:
            results.append(adopted)
            continue

        if not may_attempt(name, attempts, stamp):
            waited = int((stamp - attempts[name]) / 60)
            results.append(Attempt(name, False,
                                   "backing off — last attempt %dm ago" % waited))
            continue
        if started >= limit:
            results.append(Attempt(name, False, "deferred to a later sweep"))
            continue

        if dry_run:
            results.append(Attempt(name, False,
                                   "would clone from %s url %s" % (source, url)))
            started += 1
            continue

        # Recorded BEFORE the attempt on purpose: if this clone hangs and the process is
        # killed, or two sweeps overlap, the backoff is already in force. Recording after
        # success/failure would leave a crash-looping clone unthrottled.
        attempts[name] = stamp
        save_attempts(attempts, attempts_path)
        started += 1

        ok, detail = clone(url, destination)
        results.append(Attempt(name, ok, "%s (%s url)" % (detail, source)))
        if ok:
            # A success clears the backoff so a later legitimate re-clone is not throttled.
            attempts.pop(name, None)
            save_attempts(attempts, attempts_path)
    return results
