"""Render BOARD.md.

**This function must be deterministic.** BOARD.md is committed so that Cowork can read the
board without running Python, which means two machines regenerate it from the same
`loops/` + `journal/` and must produce byte-identical output — otherwise the file churns
and the machines fight over it (decision D-D).

So: no `now()`, no iteration over unsorted dicts, no host or path details. The header
timestamp comes from the newest journal event. Machine-local sync health deliberately does
not appear here; it goes to the gitignored SYNC.md.
"""

from typing import Any, Dict, List, Optional, Tuple

from . import duration

HEADER = "# Lodestar board"
WARNING = "<!-- Generated by bin/board.py. Never hand-edit; regenerate instead. -->"
SYNC_POINTER = (
    "Sync health is machine-local and lives in `SYNC.md` (gitignored), because a "
    "per-machine status line here would make two machines overwrite each other."
)

LoopMap = Dict[str, Tuple[Dict[str, str], str]]


def board(loop_map: LoopMap, newest_ts: Optional[str] = None,
          problems: Optional[List[Tuple[str, str]]] = None,
          shadow_line: Optional[str] = None) -> str:
    """Return the full text of BOARD.md.

    `shadow_line` is one optional line summarising unattended shadow runs, built by
    `lib.shadow.board_line` from the same journal events the caller already loaded. One line
    and not the digest itself: BOARD.md's contract is to stay small and byte-stable, and a
    14-day growing document inside it would churn. The detail lives in `airlock/DIGEST.md`.
    """
    lines = [HEADER, "", WARNING, ""]
    lines.append("As of **%s**" % (newest_ts or "(no events yet)"))
    lines.append("")

    active = _select(loop_map, "active", "open")
    background = _select(loop_map, "background", "open")
    parked = _by_state(loop_map, "parked")
    closed = _by_state(loop_map, "closed")

    lines.extend(_active_section(active))
    lines.extend(_simple_section(
        "## 🟢 Background — %d" % len(background),
        background,
        "Make progress when you can. Uncapped.",
    ))
    if parked:
        lines.extend(_simple_section(
            "## ⏸ Parked — %d" % len(parked), parked,
            "Set aside deliberately; not consuming a WIP slot.",
        ))
    if closed:
        lines.extend(_closed_section(closed))

    if shadow_line:
        # Under the closed section, because unattended bookkeeping is the least of the
        # board's news and must not push the WIP-capped 🔴 table down the page.
        lines.append(shadow_line)
        lines.append("")

    if problems:
        lines.append("## ⚠ Journal problems")
        lines.append("")
        for path, reason in sorted(problems):
            lines.append("- `%s` — %s" % (path, reason))
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(SYNC_POINTER)
    return "\n".join(lines) + "\n"


def summary(loop_map: LoopMap) -> str:
    """One-line console summary printed after a touch or close.

    Deliberately short: the ritual asks every command to surface loop status, and a wall of
    text after every touch would train the user to ignore it.
    """
    active = _select(loop_map, "active", "open")
    background = _select(loop_map, "background", "open")
    parked = _by_state(loop_map, "parked")

    parts = ["🔴 %d" % len(active), "🟢 %d" % len(background)]
    if parked:
        parts.append("⏸ %d" % len(parked))
    line = "   board: " + "  ".join(parts)
    if active:
        line += "\n   active: " + ", ".join(loop_id for loop_id, _ in active)
    return line


def _select(loop_map: LoopMap, loop_class: str, state: str) -> List[Tuple[str, Dict[str, str]]]:
    chosen = [
        (loop_id, fields)
        for loop_id, (fields, _) in loop_map.items()
        if fields.get("class") == loop_class and fields.get("state") == state
    ]
    return sorted(chosen, key=lambda pair: pair[0])


def _by_state(loop_map: LoopMap, state: str) -> List[Tuple[str, Dict[str, str]]]:
    chosen = [
        (loop_id, fields)
        for loop_id, (fields, _) in loop_map.items()
        if fields.get("state") == state
    ]
    return sorted(chosen, key=lambda pair: pair[0])


def _active_section(active: List[Tuple[str, Dict[str, str]]]) -> List[str]:
    lines = ["## 🔴 Active — %d" % len(active), ""]
    if not active:
        lines.append("_Nothing active._")
        lines.append("")
        return lines
    lines.extend(_table(active, deadline=True))
    return lines


def _simple_section(heading: str, rows: List[Tuple[str, Dict[str, str]]],
                    blurb: str) -> List[str]:
    lines = [heading, "", "_%s_" % blurb, ""]
    if not rows:
        lines.append("_None._")
        lines.append("")
        return lines
    lines.extend(_table(rows, deadline=False))
    return lines


def _closed_section(closed: List[Tuple[str, Dict[str, str]]]) -> List[str]:
    # Newest first by last_touch, id breaking ties so the order is reproducible.
    ordered = sorted(closed, key=lambda pair: (pair[1].get("last_touch", ""), pair[0]),
                     reverse=True)[:10]
    lines = ["## ✅ Recently closed — %d" % len(closed), ""]
    lines.append("| Loop | Title | est_close | actual_spent | Closed |")
    lines.append("|------|-------|-----------|--------------|--------|")
    for loop_id, fields in ordered:
        lines.append("| `%s` | %s | %s | %s | %s |" % (
            loop_id,
            _cell(fields.get("title")) or loop_id,
            _cell(fields.get("est_close")) or "—",
            _cell(fields.get("actual_spent")) or "—",
            _cell(fields.get("last_touch")) or "—",
        ))
    lines.append("")
    return lines


def _table(rows: List[Tuple[str, Dict[str, str]]], deadline: bool) -> List[str]:
    if deadline:
        lines = ["| Loop | Title | Deadline | est_close | Last touch |",
                 "|------|-------|----------|-----------|------------|"]
    else:
        lines = ["| Loop | Title | est_close | Last touch |",
                 "|------|-------|-----------|------------|"]

    for loop_id, fields in rows:
        est = _est_cell(fields.get("est_close"))
        cells = ["`%s`" % loop_id, _cell(fields.get("title")) or loop_id]
        if deadline:
            cells.append(_cell(fields.get("deadline")) or "—")
        cells.append(est)
        cells.append(_cell(fields.get("last_touch")) or "—")
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    return lines


def _est_cell(est: Optional[str]) -> str:
    """est_close, flagged when tiny and called out when missing.

    Ritual section 3 wants time-to-close surfaced everywhere, and a missing estimate shown
    as missing rather than quietly blank.
    """
    if not est:
        return "⚠ unset"
    if duration.is_just_do_it(est):
        return "%s — **just do it now**" % _cell(est)
    return _cell(est)


def _cell(value: Any) -> str:
    """Escape a value for a markdown table cell."""
    if value is None:
        return ""
    return str(value).replace("|", "\\|").replace("\n", " ").strip()
