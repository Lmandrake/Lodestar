    skills.set_defaults(func=cmd_skills)

    settings_cmd = sub.add_parser("settings", help="report/seed/accept settings.json sync")
    settings_cmd.add_argument("--seed", action="store_true",
                              help="rebuild claude/settings-base.json from this machine + peers")
    settings_cmd.add_argument("--adopt", action="store_true",
                              help="accept the rendered settings on this machine (captures first)")
