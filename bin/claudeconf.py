#!/usr/bin/env python3
"""Keep ~/.claude under version control.

    claudeconf.py render     # write ~/.claude/CLAUDE.md from claude/global/
    claudeconf.py check      # exit 1 if the live file drifted or a snapshot is stale
    claudeconf.py snapshot   # copy settings.json, statusline.sh, and auto-memory into the repo
    claudeconf.py import     # rebuild claude/global/ FROM the live file (recovery)
    claudeconf.py preview    # what WOULD this machine's file be, and what would it lose? (read-only)

`~/.claude/CLAUDE.md` holds the session-onboarding rule and the save-as-you-go authorization,
and `~/.claude` is not a git repo, so none of it was versioned or backed up.

**Why render a real file instead of symlinking or importing.** Claude Code's memory docs are
explicit: in Cowork sessions it *skips* a `~/.claude/CLAUDE.md` that is a symlink, and *skips*
any `@import` in a user-scope file resolving outside the session's working directory. Both
failures are silent. Since Cowork is half of Lodestar's two-runtime split, the ritual would
quietly stop applying in exactly the runtime that most needs it. So the live file stays a
plain, real file and this renders it — the same source-of-truth-in-a-repo pattern Waypoint
uses for `~/.zshrc`, including the reverse `import` recovery path.

**Machine-specific content is separated on purpose.** A typical live file opens with "This machine
is the desktop … no battery, no lid", which is actively wrong on a laptop. The machine
section comes from `claude/global/machines/<key>.md`, keyed the same way as `machines.md`.

**Auto-memory is snapshotted, not linked.** Claude rewrites those files mid-session on both
machines at identical paths; sharing them live would mean a permanent merge war over what are
semantically just notes. So `snapshot` copies them in and `restore-memory` is deliberately
manual.
"""

